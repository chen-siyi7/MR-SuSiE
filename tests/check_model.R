a <- grep('^--file=',commandArgs(),value=TRUE)
root <- normalizePath(file.path(dirname(gsub('~+~',' ',sub('^--file=','',a[1]),fixed=TRUE)),'..'))
source(file.path(root,'R/load.R'))
source(file.path(root,'R/analysis_helpers.R'))
model <- make_mr_susie(root,file.path(root,'runtime/tests'))
x <- jsonlite::read_json(file.path(root,'examples/joint_strong_0001.json'),simplifyVector=TRUE)
m <- nrow(x$B)
k <- ncol(x$B)
fit <- model$fit(x$B,matrix(x$sx,m,k),x$y,rep(x$sy,m),x$R,x$Sigma,
  x$selection_y,rep(x$sy,m),10000,rep('Outcome SD per exposure SD',k))
expected <- read.csv(file.path(root,'examples/joint_strong_0001_expected.csv'))
stopifnot(isTRUE(all.equal(as.matrix(data.frame(point=fit$point,fit$score_inference)),as.matrix(expected),tolerance=1e-9,check.attributes=FALSE)))
stopifnot(max(abs(fit$point-fit$score_inference$center))>.01)
stopifnot(isTRUE(all.equal((fit$score_inference$lower+fit$score_inference$upper)/2,fit$score_inference$center,tolerance=1e-12)))
failed <- mr_susie_rows(NULL,'MVMR-SuSiE','conditional_direct_effect',paste0('x',1:3),error='test_failure')
stopifnot(nrow(failed)==3L,all(is.na(failed$beta)),all(!failed$point_available),all(!failed$test_available),all(failed$error=='test_failure'))
cat('Numerical fixture, interval-center and unavailable-result checks passed\n')
